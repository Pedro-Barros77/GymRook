"""Round-4 isolated adapter: prepare, review frames, then explicitly export.

The round-3 code is imported in memory with new paths. Its files, sources,
outputs and media remain read-only. Restored incline-press media is never an
input to this builder and cannot be regenerated by it.
"""
from pathlib import Path
import argparse
import hashlib
import importlib.util
import json
import sys

ROOT = Path(__file__).resolve().parent.parent
CONFIG = ROOT/'docs/generated-frames-v4-followup/config.json'
WORK = ROOT/'output/followup-round4'
MEDIA = ROOT/'dist/assets/animations-v4'
REPORT = ROOT/'docs/followup-animations-build.json'
REVIEW = ROOT/'docs/generated-frames-v4-followup/final-release-review.json'
ENGINE = ROOT/'scripts/build-repair-animations.py'


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def module(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    result = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(result)
    return result


def read(path):
    return json.loads(path.read_text(encoding='utf-8'))


IDS = tuple(read(CONFIG)['exercises'])
if 'incline-dumbbell-press' in IDS or 'alternating-lunge' in IDS:
    raise ValueError('Restored press and approved lunge are excluded from round4.')

implementation = module('round4_readonly_round3_engine', ENGINE)
implementation.CONFIG, implementation.WORK = CONFIG, WORK
implementation.MEDIA, implementation.REPORT = MEDIA, REPORT
implementation.IDS = IDS
implementation.__file__ = str(Path(__file__).resolve())
configured_engine = implementation.configured_engine
frame_spec_digest = implementation.frame_spec_digest
original_write = implementation.write


def checked_dependencies():
    config = read(CONFIG)
    for entry in config['readonlyEngineDependencies']:
        path = ROOT/entry['file']
        if not path.is_file() or digest(path) != entry['sha256']:
            raise ValueError('Read-only engine dependency changed: '+entry['file'])
    if (config['fps'], config['size']) != (12, 512):
        raise ValueError('Round4 is fixed at12fps and512square.')
    for name, spec in config['exercises'].items():
        if spec['frameCount'] != 36 or spec['cycle'] != 'ping-pong':
            raise ValueError('Round4 expects36frame/3s ping-pong cycles: '+name)
        if spec.get('prepareReady'):
            path = ROOT/spec['sheet']
            if not path.is_file() or digest(path) != spec['sheetSha256']:
                raise ValueError('Reviewed source is absent or changed: '+name)
    return config


def release_metadata(report, engine):
    path = MEDIA/'manifest.json'
    if not path.exists():
        report['publicationStage'] = 'source-or-motion-review'
        return
    manifest = engine.read_json(path)
    coverage = manifest['coverage']
    report['coverage'] = coverage
    if report['stage'] != 'encoded':
        report['publicationStage'] = 'source-or-motion-review'
        return
    report['publicationStage'] = 'complete' if coverage['complete'] else 'partial-export'
    manifest['publicationStage'] = report['publicationStage']
    manifest['pipeline'] = 'Reviewed colored image_gen raster sources, local interpolation or exact reviewed PNGs, and canonical fixed regions;12fps.'
    if coverage['complete']:
        review = read(REVIEW)
        verdicts = {a['id']: a for a in review['animations']}
        records = {a['id']: a for a in report['animations']}
        if not review.get('complete') or set(verdicts) != set(IDS):
            raise ValueError('Final visual index must cover every round4 animation.')
        for name in IDS:
            record, verdict = records[name], verdicts[name]
            actual = hashlib.sha256(b''.join(bytes.fromhex(f['sha256']) for f in record['frames'])).hexdigest()
            if verdict['verdict'] != 'PASS' or verdict['sourceSha256'] != record['sourceSha256'] or verdict['frameDigestBin32'] != actual:
                raise ValueError('Visual review does not match frozen source/frames: '+name)
            for entry in verdict.get('reviewEvidence', []):
                if digest(ROOT/entry['file']) != entry['sha256']:
                    raise ValueError('Visual review evidence changed: '+entry['file'])
        reference = {'file':engine.label(REVIEW), 'sha256':digest(REVIEW),
                     'reviewedAnimationCount':len(IDS), 'scope':review['scope']}
        manifest['visualReview'] = report['visualReview'] = reference
    engine.write_json(path, manifest)


def write(path, data):
    if path == REPORT:
        data['method'] = {
            'timeline':'19 reviewed forward PNGs plus17 byte-exact return PNGs;36frames/3s at12fps.',
            'scope':'Only round4 assets; earlier media and restored press remain unchanged.',
            'qaLimit':'Pixel continuity and encoding checks do not certify exercise mechanics or anatomy.'}
        data['readonlyAdapter'] = {'file':ENGINE.relative_to(ROOT).as_posix(), 'sha256':digest(ENGINE)}
    original_write(path, data)


implementation.release_metadata = release_metadata
implementation.write = write


def main():
    config = checked_dependencies()
    if sys.argv[1:] == ['--preflight']:
        print(json.dumps({'passed':True, 'expectedIds':list(IDS),
                          'prepareReady':[n for n,s in config['exercises'].items() if s.get('prepareReady')],
                          'mediaDirectory':MEDIA.relative_to(ROOT).as_posix(),
                          'readOnlyEngineDependencies':len(config['readonlyEngineDependencies'])}, indent=2))
        return
    implementation.main()


if __name__ == '__main__':
    main()
